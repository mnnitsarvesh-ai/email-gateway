import { describe, expect, it } from 'vitest';
import {
  REPORT_ATTACHMENT_HINT,
  REPORT_PORTAL_NOTE,
  renderReportEmailText,
  reportAttachmentName,
  reportEmailMessageId,
  reportEmailSubject,
  reportFigures,
  reportPortalLink,
} from './assistant-report-templates';

const REPORT = '0193a1b2-4f50-7a61-8b72-9c8d7e6f5a41';
const DELIVERY = '0193a1b2-5a61-7b72-9c83-0d9e8f7a6b52';
const facts = {
  reportPublicId: REPORT,
  title: 'Security report: Acme (Last 7 days)',
  organizationName: 'Acme Corp',
  periodFrom: new Date('2026-11-16T00:00:00.000Z'),
  periodTo: new Date('2026-11-23T09:30:00.000Z'),
  figures: [
    { label: 'Messages processed', value: '1,248' },
    { label: 'Threats blocked', value: '37' },
  ],
  portalUrl: 'https://portal.test',
};

describe('assistant report email subject (step AI-R D8)', () => {
  it('names the organization and the UTC period', () => {
    expect(reportEmailSubject(facts)).toBe(
      'Security report: Acme Corp (2026-11-16 00:00 to 2026-11-23 09:30 UTC)',
    );
  });

  it('removes CR/LF, control, bidi and angle-bracket characters and stays ≤ 200 characters', () => {
    const subject = reportEmailSubject({
      ...facts,
      organizationName: 'Evil\r\nBcc: victim@other.example\u202e<b>\u0007',
    });
    const unsafe = [...subject].filter(
      (ch) => ch.codePointAt(0)! < 0x20 || ch === '\u202e' || ch === '<' || ch === '>',
    );
    expect(unsafe).toEqual([]);
    expect(subject).toBe(
      'Security report: EvilBcc: victim@other.exampleb (2026-11-16 00:00 to 2026-11-23 09:30 UTC)',
    );
    const long = reportEmailSubject({ ...facts, organizationName: 'x'.repeat(1000) });
    expect(long.length).toBeLessThanOrEqual(200);
    expect(long.startsWith('Security report: xxx')).toBe(true);
    expect(reportEmailSubject({ ...facts, organizationName: '\r\n' })).toContain(
      'Security report: your organization (',
    );
  });
});

describe('assistant report email text part', () => {
  it('is the fixed template: title, period, figures, attachment hint and the portal link', () => {
    expect(renderReportEmailText(facts)).toBe(
      [
        'Security report: Acme (Last 7 days)',
        '',
        'Organization: Acme Corp',
        'Period: 2026-11-16 00:00 to 2026-11-23 09:30 UTC',
        '',
        'Summary:',
        '- Messages processed: 1,248',
        '- Threats blocked: 37',
        '',
        REPORT_ATTACHMENT_HINT,
        '',
        `Portal: https://portal.test/assistant/reports/${REPORT} ${REPORT_PORTAL_NOTE}`,
        '',
        'This report was generated by the email gateway assistant at the request of a user of your organization. This is an automated message; replies are not read.',
      ].join('\n'),
    );
  });

  it('never lets row text inject lines and drops malformed figures', () => {
    const text = renderReportEmailText({
      ...facts,
      title: 'T\r\nInjected: line',
      figures: [
        { label: 'ok', value: '1' },
        { label: 'n', value: 2 },
        'x',
        null,
        { label: 'L\nX', value: 'V\r\nY' },
        ...Array.from({ length: 20 }, (_, i) => ({ label: `f${String(i)}`, value: '0' })),
      ],
    });
    expect(text.split('\n')[0]).toBe('TInjected: line');
    expect(text).not.toMatch(/^Injected/m);
    expect(text).toContain('- LX: VY');
    expect(text.match(/^- /gm)).toHaveLength(8);
    expect(renderReportEmailText({ ...facts, figures: { not: 'an array' } })).not.toContain(
      'Summary:',
    );
    expect(renderReportEmailText({ ...facts, title: '' }).split('\n')[0]).toBe('Security report');
  });

  it('reads figures leniently (strings only, bounded)', () => {
    expect(reportFigures(null)).toEqual([]);
    expect(reportFigures([{ label: 'a'.repeat(100), value: 'b' }])[0]!.label).toHaveLength(64);
    expect(reportFigures([{ label: '', value: 'b' }])).toEqual([]);
  });
});

describe('assistant report attachment, link and Message-ID', () => {
  it('names the attachment by the UTC generation date', () => {
    expect(reportAttachmentName(new Date('2026-11-23T23:59:59.999Z'))).toBe(
      'security-report-2026-11-23.html',
    );
    expect(reportAttachmentName(new Date('2026-01-05T00:00:00.000Z'))).toBe(
      'security-report-2026-01-05.html',
    );
  });

  it('links the owner-only portal view', () => {
    expect(reportPortalLink('https://portal.test', REPORT)).toBe(
      `https://portal.test/assistant/reports/${REPORT}`,
    );
  });

  it('is <assistant-report.<deliveryId>@<From domain>>', () => {
    expect(reportEmailMessageId(DELIVERY, 'Email Gateway <no-reply@Gateway.Test>')).toBe(
      `<assistant-report.${DELIVERY}@gateway.test>`,
    );
    expect(reportEmailMessageId(DELIVERY, 'no-reply@gw.example')).toBe(
      `<assistant-report.${DELIVERY}@gw.example>`,
    );
    expect(reportEmailMessageId(DELIVERY, 'nobody')).toBe(`<assistant-report.${DELIVERY}@nobody>`);
  });
});
