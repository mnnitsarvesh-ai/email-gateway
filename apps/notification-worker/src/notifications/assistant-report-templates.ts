import { safeText } from './templates';

/**
 * The fixed parts of the assistant report email (step AI-R D8, docs/plan/steps/
 * 31-ai-chat-reports.md): the subject, the plain-text alternative, the attachment name and the
 * Message-ID. The HTML part and the attachment are the stored report bytes (rendered and
 * allow-listed by `@email-gateway/assistant`, D4); everything here comes from the report row and
 * the organization name, reduced to printable single-line text (`safeText`) so database text can
 * never inject a header or a body line. Never the recipient address.
 */

/** Longest subject (characters), CR/LF and control characters removed (D8). */
export const REPORT_SUBJECT_MAX = 200;
/** Most figures listed in the text part (the card holds ≤ 8, D2 step 11). */
export const REPORT_TEXT_MAX_FIGURES = 8;
export const REPORT_ATTACHMENT_HINT =
  'The full report is attached as an HTML file; open it in a browser if your mail client does not show the charts.';
export const REPORT_PORTAL_NOTE = '(only the person who generated it can open it in the portal)';

export interface ReportFigureLine {
  label: string;
  value: string;
}

export interface ReportEmailFacts {
  reportPublicId: string;
  title: string;
  organizationName: string;
  periodFrom: Date;
  periodTo: Date;
  /** `ai_chat_reports.figures` (untrusted JSON; read leniently). */
  figures: unknown;
  portalUrl: string;
}

const pad = (n: number) => String(n).padStart(2, '0');

/** `YYYY-MM-DD HH:MM` in UTC. */
export function utcMinute(date: Date): string {
  return `${utcDay(date)} ${pad(date.getUTCHours())}:${pad(date.getUTCMinutes())}`;
}

/** `YYYY-MM-DD` in UTC. */
export function utcDay(date: Date): string {
  return `${String(date.getUTCFullYear())}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())}`;
}

/**
 * The summary figures of the row (`[{ label, value }]`, ≤ 8, both strings); anything else in the
 * JSON is ignored. Labels and values are printable, single-line and bounded.
 */
export function reportFigures(value: unknown): ReportFigureLine[] {
  if (!Array.isArray(value)) return [];
  const out: ReportFigureLine[] = [];
  for (const item of value) {
    if (out.length >= REPORT_TEXT_MAX_FIGURES) break;
    if (item === null || typeof item !== 'object') continue;
    const { label, value: v } = item as { label?: unknown; value?: unknown };
    if (typeof label !== 'string' || typeof v !== 'string') continue;
    const line = { label: safeText(label, 64), value: safeText(v, 64) };
    if (line.label && line.value) out.push(line);
  }
  return out;
}

/** `Security report: <organization> (<from> to <to> UTC)`, sanitized, ≤ 200 characters. */
export function reportEmailSubject(
  facts: Pick<ReportEmailFacts, 'organizationName' | 'periodFrom' | 'periodTo'>,
): string {
  const organization = safeText(facts.organizationName, 120) || 'your organization';
  return safeText(
    `Security report: ${organization} (${utcMinute(facts.periodFrom)} to ${utcMinute(facts.periodTo)} UTC)`,
    REPORT_SUBJECT_MAX,
  );
}

/** `${PORTAL_PUBLIC_URL}/assistant/reports/<reportId>` (the owner-only portal view, D9). */
export function reportPortalLink(portalUrl: string, reportPublicId: string): string {
  return `${portalUrl}/assistant/reports/${encodeURIComponent(reportPublicId)}`;
}

/** The fixed plain-text part. */
export function renderReportEmailText(facts: ReportEmailFacts): string {
  const figures = reportFigures(facts.figures);
  const organization = safeText(facts.organizationName, 120) || 'your organization';
  return [
    safeText(facts.title, 200) || 'Security report',
    '',
    `Organization: ${organization}`,
    `Period: ${utcMinute(facts.periodFrom)} to ${utcMinute(facts.periodTo)} UTC`,
    ...(figures.length > 0
      ? ['', 'Summary:', ...figures.map((f) => `- ${f.label}: ${f.value}`)]
      : []),
    '',
    REPORT_ATTACHMENT_HINT,
    '',
    `Portal: ${reportPortalLink(facts.portalUrl, facts.reportPublicId)} ${REPORT_PORTAL_NOTE}`,
    '',
    'This report was generated by the email gateway assistant at the request of a user of your organization. This is an automated message; replies are not read.',
  ].join('\n');
}

/** `security-report-<yyyy-mm-dd>.html` (UTC date the report was generated). */
export function reportAttachmentName(generatedAt: Date): string {
  return `security-report-${utcDay(generatedAt)}.html`;
}

/** `<assistant-report.<deliveryId>@<domain of the From address>>` (one per delivery). */
export function reportEmailMessageId(deliveryPublicId: string, from: string): string {
  const address = /<([^>]+)>/.exec(from)?.[1] ?? from;
  const domain =
    address
      .slice(address.lastIndexOf('@') + 1)
      .trim()
      .toLowerCase() || 'localhost';
  return `<assistant-report.${deliveryPublicId}@${domain}>`;
}
