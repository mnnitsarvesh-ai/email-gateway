/**
 * Every SMTP/LMTP reply and Postfix policy/socketmap answer text of the step 2.2 mail path
 * (docs/plan/steps/04-smtp-gateway.md D2, D4, D7, D10, D11, D13), in one place.
 *
 * Invariant 7 (§2.0): replies are generic. They never contain internal error details, tenant
 * names or ids. Add new texts here; never build reply text from exception messages or data.
 */

/** An SMTP/LMTP reply: numeric code and text (enhanced status code first). */
export interface SmtpReply {
  readonly code: number;
  readonly text: string;
}

/** `<code> <text>` as sent on the wire (without CRLF). */
export const replyLine = (reply: SmtpReply): string => `${reply.code} ${reply.text}`;

/** An error carrying the reply, as smtp-server expects for per-recipient LMTP failures. */
export interface SmtpReplyError extends Error {
  responseCode: number;
}

export function replyError(reply: SmtpReply): SmtpReplyError {
  return Object.assign(new Error(reply.text), { responseCode: reply.code });
}

