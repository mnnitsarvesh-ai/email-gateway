function op(
  name: string,
  label: string,
  phrase: string,
  valueShape: string,
  itemKind: string | null,
  maxItems: number | null,
  maxItemLength: number | null,
  description: string,
) {
  const negated = name === 'not_in';
  return {
    op: name,
    label,
    phrase,
    valueShape,
    itemKind,
    maxItems,
    maxItemLength,
    negated,
    allowedInException: !negated,
    description,
  };
}

function param(
  name: string,
  label: string,
  type: string,
  required: boolean,
  extra: {
    values?: string[];
    default?: string | boolean;
    minLength?: number;
    maxLength?: number;
    pattern?: string;
    description?: string;
  } = {},
) {
  return {
    name,
    label,
    type,
    required,
    values: extra.values ?? null,
    default: extra.default ?? null,
    minLength: extra.minLength ?? null,
    maxLength: extra.maxLength ?? null,
    pattern: extra.pattern ?? null,
    description: extra.description ?? '',
  };
}

function action(
  type: string,
  label: string,
  phrase: string,
  kind: string,
  disposition: string | null,
  params: ReturnType<typeof param>[],
) {
  return { type, label, phrase, kind, disposition, params, description: `${label}.` };
}

