#!/usr/bin/env node
// Generates the portal's typed API client inputs from the OpenAPI snapshot (design P7, ADR-0058).
//
//   node scripts/generate-api.mjs           writes src/lib/api/schema.gen.ts and operations.gen.ts
//   node scripts/generate-api.mjs --check   regenerates in memory; exit 1 with a diff summary when
//                                           the committed files differ (build, typecheck, Vitest)
//
// Input: ../../docs/api/openapi.json (the only contract the portal may use). Output is formatted
// with the repository Prettier config and is deterministic (operations sorted by operationId,
// matchers by specificity), so the check never flaps.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appDir = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SNAPSHOT_PATH = join(appDir, '../../docs/api/openapi.json');
export const SCHEMA_OUT = join(appDir, 'src/lib/api/schema.gen.ts');
export const OPERATIONS_OUT = join(appDir, 'src/lib/api/operations.gen.ts');

const HEADER = `// Generated by \`pnpm --filter @email-gateway/admin-portal api:generate\` from docs/api/openapi.json.
// Do not edit: change the API, regenerate the snapshot, then run the command again.
`;

const METHODS = ['get', 'put', 'post', 'delete', 'patch'];
/** Operations whose request or response carries a token: the BFF session routes own them (P5). */
const BFF_ONLY = [
  'AuthController_login_v1',
  'AuthController_verifyMfa_v1',
  'AuthController_refresh_v1',
  'AuthController_logout_v1',
  'AuthController_logoutAll_v1',
  'PlatformOverrideController_start_v1',
  'PlatformOverrideController_end_v1',
];

function normalizePermissions(value) {
  if (value == null) return null;
  const list = Array.isArray(value) ? value : [value];
  return list.map((entry) => ({
    mode: entry.mode === 'any' ? 'any' : 'all',
    permissions: [...entry.permissions],
  }));
}

function listKeyOf(operation) {
  const schema = operation.responses?.['200']?.content?.['application/json']?.schema;
  const props = schema?.properties ?? {};
  if (props.data?.type === 'array') return 'data';
  if (props.items?.type === 'array') return 'items';
  return null;
}

function sortValuesOf(operation) {
  const param = (operation.parameters ?? []).find((p) => p.in === 'query' && p.name === 'sort');
  if (!param) return null;
  const values = param.schema?.enum;
  return Array.isArray(values) ? [...values] : [];
}

/** Extracts the operation table from the snapshot (pure; exported for tests). */
export function extractOperations(spec) {
  const out = [];
  for (const path of Object.keys(spec.paths ?? {})) {
    for (const method of METHODS) {
      const op = spec.paths[path][method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
      const security = op.security;
      out.push({
        operationId: op.operationId,
        method: method.toUpperCase(),
        path,
        tag: op.tags?.[0] ?? null,
        permissions: normalizePermissions(op['x-eg-permissions']),
        public: !security || security.length === 0,
        idempotency: op['x-eg-idempotency'] ?? null,
        cursor: op['x-eg-cursor'] ?? null,
        rateClass: op['x-eg-rate-class'] ?? null,
        returnsSecret: op['x-eg-returns-secret'] === true,
        secretReplay: op['x-eg-secret-replay'] ?? null,
        listKey: listKeyOf(op),
        sort: sortValuesOf(op),
        bffOnly: BFF_ONLY.includes(op.operationId),
      });
    }
  }
  out.sort((a, b) => (a.operationId < b.operationId ? -1 : a.operationId > b.operationId ? 1 : 0));
  const ids = new Set();
  for (const op of out) {
    if (ids.has(op.operationId)) throw new Error(`Duplicate operationId ${op.operationId}`);
    ids.add(op.operationId);
  }
  for (const id of BFF_ONLY) {
    if (!ids.has(id)) throw new Error(`BFF-only operation ${id} is missing from the snapshot`);
  }
  return out;
}

/** Matchers sorted so static segments win over parameters at the first difference. */
export function buildMatchers(operations) {
  const matchers = operations.map((op) => ({
    method: op.method,
    segments: op.path
      .replace(/^\/api\/v1\//, '')
      .split('/')
      .map((s) => (/^\{[^}]+\}$/.test(s) ? { param: s.slice(1, -1) } : s)),
    operationId: op.operationId,
  }));
  const key = (m) =>
    m.segments.map((s) => (typeof s === 'string' ? `0${s}` : '1')).join('/') + `|${m.method}`;
  matchers.sort((a, b) => (key(a) < key(b) ? -1 : key(a) > key(b) ? 1 : 0));
  return matchers;
}

async function format(source, filepath) {
  const prettier = await import('prettier');
  const config = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(source, { ...config, filepath });
}

/** Returns `{ [absolutePath]: content }` for both generated files. */
export async function generate(specText) {
  const text = specText ?? (await readFile(SNAPSHOT_PATH, 'utf8'));
  const spec = JSON.parse(text);
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(spec, { alphabetize: true });
  const schemaSource = `${HEADER}\n${astToString(ast)}`;

  const operations = extractOperations(spec);
  const matchers = buildMatchers(operations);
  const operationsSource = `${HEADER}
import type { OperationMeta, RouteMatcher } from './operation-types';

/** Snapshot facts: ${operations.length} operations, OpenAPI ${spec.openapi}, API ${spec.info?.version ?? 'unknown'}. */
export const OPERATION_COUNT = ${operations.length};

export const operations = {
${operations.map((op) => `  ${op.operationId}: ${JSON.stringify(op)},`).join('\n')}
} as const satisfies Record<string, OperationMeta>;

export type OperationId = keyof typeof operations;

export const OPERATION_IDS = Object.keys(operations) as OperationId[];

/** Allow-list of the BFF proxy (P5), most specific first. */
export const routeMatchers: readonly RouteMatcher<OperationId>[] = [
${matchers.map((m) => `  ${JSON.stringify(m)},`).join('\n')}
];
`;
  return {
    [SCHEMA_OUT]: await format(schemaSource, SCHEMA_OUT),
    [OPERATIONS_OUT]: await format(operationsSource, OPERATIONS_OUT),
  };
}

function diffSummary(expected, actual) {
  const a = expected.split('\n');
  const b = actual.split('\n');
  const max = Math.max(a.length, b.length);
  let first = -1;
  let changed = 0;
  for (let i = 0; i < max; i += 1) {
    if (a[i] !== b[i]) {
      changed += 1;
      if (first === -1) first = i;
    }
  }
  if (first === -1) return 'identical';
  return `${changed} line(s) differ, first at line ${first + 1}: expected ${JSON.stringify(
    (a[first] ?? '<eof>').slice(0, 120),
  )}, found ${JSON.stringify((b[first] ?? '<eof>').slice(0, 120))}`;
}

/** Compares the generated output with the files on disk; returns the drifted files. */
export async function check(specText) {
  const files = await generate(specText);
  const drift = [];
  for (const [path, expected] of Object.entries(files)) {
    let actual = '';
    try {
      actual = await readFile(path, 'utf8');
    } catch {
      actual = '';
    }
    if (actual !== expected) drift.push({ path, summary: diffSummary(expected, actual) });
  }
  return drift;
}

async function main() {
  const isCheck = process.argv.includes('--check');
  if (isCheck) {
    const drift = await check();
    if (drift.length > 0) {
      for (const d of drift) {
        console.error(`api:check: ${relative(appDir, d.path)} is out of date (${d.summary})`);
      }
      console.error(
        'api:check: docs/api/openapi.json changed; run `pnpm --filter @email-gateway/admin-portal api:generate` and fix the compile errors.',
      );
      process.exit(1);
    }
    console.log('api:check: generated client matches docs/api/openapi.json');
    return;
  }
  const files = await generate();
  for (const [path, content] of Object.entries(files)) {
    await writeFile(path, content);
    console.log(`api:generate: wrote ${relative(appDir, path)}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
