import { Inject, Injectable } from '@nestjs/common';
import {
  generateJournalIntakeGuide,
  type JournalIntakeGuide,
  journalIntakeGuideFileName,
  renderJournalIntakeGuideMarkdown,
} from '@email-gateway/provider-integrations';
import { API_CONFIG } from '../../../api-config.token';
import type { Principal } from '../../../auth-contracts/principal';
import type { TenantScope } from '../../../auth-contracts/tenant-scope';
import { JOURNAL_PERMISSIONS as P, type JournalingConfig } from '../journaling.constants';
import { journalIntakeUnavailable } from '../journaling.errors';
import { IntakeAddressService } from './intake-address.service';
import { IntakeSourcesService } from './intake-sources.service';

/** The Markdown rendering of a guide with its download name. */
export interface MarkdownGuide {
  fileName: string;
  markdown: string;
}

/**
 * Customer-specific journal intake guides (step 8.6 D10; the 8.2 guide framework, ADR-0080):
 * `journal-intake-guide/1` generated by the pure WP2 generator from the source's own values (kind,
 * address, Google header token, the bound connection, the verified — for provider kinds linked —
 * domains, the registered networks, TLS, the gateway MX hosts the intake domain points to,
 * attestations). The address and token are revealed only to `journal:manage` holders (each such
 * guide is audited `journal_intake.address_revealed`, `via: guide`); masked otherwise. The
 * gateway never applies a step of a guide.
 */
@Injectable()
export class IntakeGuideService {
  constructor(
    @Inject(API_CONFIG) private readonly config: Pick<JournalingConfig, 'GATEWAY_MX_HOSTS'>,
    private readonly sources: IntakeSourcesService,
    private readonly addresses: IntakeAddressService,
  ) {}

  now(): Date {
    return new Date();
  }

  async guide(
    principal: Principal,
    scope: TenantScope,
    rawId: unknown,
    sourceIp: string | null,
  ): Promise<JournalIntakeGuide> {
    if (!this.addresses.available) throw journalIntakeUnavailable();
    const facts = await this.sources.guideFacts(scope, rawId);
    const row = facts.row;
    const reveal = principal.permissions.has(P.manage);
    const credentials = this.addresses.derive(
      row.publicId,
      row.addressVersion,
      row.kind === 'google_workspace_copy',
    );
    if (reveal) await this.sources.recordReveal(principal, scope, row, 'guide', sourceIp);
    return generateJournalIntakeGuide({
      kind: row.kind,
      source: { publicId: row.publicId, displayName: row.displayName },
      address: credentials.address,
      headerToken: credentials.headerToken,
      reveal,
      connection:
        facts.connection === null
          ? null
          : {
              displayName: facts.connection.displayName,
              tenantId: facts.connection.externalTenantId,
            },
      domains: facts.domains,
      networks: facts.networks,
      requireTls: row.requireTls,
      gateway: { mxHosts: this.config.GATEWAY_MX_HOSTS.map((mx) => mx.host) },
      attestations: facts.attestations.map((a) => ({ code: a.code, at: a.at })),
      generatedAt: this.now(),
    });
  }

  async markdown(
    principal: Principal,
    scope: TenantScope,
    rawId: unknown,
    sourceIp: string | null,
  ): Promise<MarkdownGuide> {
    const guide = await this.guide(principal, scope, rawId, sourceIp);
    return {
      fileName: journalIntakeGuideFileName(guide),
      markdown: renderJournalIntakeGuideMarkdown(guide),
    };
  }
}
