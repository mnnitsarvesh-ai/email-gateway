import { Inject, Injectable } from '@nestjs/common';
import {
  type ApiModeGuide,
  apiModeAttestationsFor,
  apiModeGuideFileName,
  generateApiModeGuide,
  type JournalIntakeKind,
  type ProviderAuthMethod,
  renderApiModeGuideMarkdown,
} from '@email-gateway/provider-integrations';
import { API_CONFIG } from '../../../api-config.token';
import type { TenantScope } from '../../../auth-contracts/tenant-scope';
import { IntakeAddressService } from '../../journaling/services/intake-address.service';
import { attestationsOf } from '../../provider-connections/provider-connections.mapper';
import type { ApiModeConfig } from '../api-mode.constants';
import { connectionNotFound } from '../api-mode.errors';
import { ApiModeRepository, type ConnectionFacts } from '../repositories/api-mode.repository';
import { parsePublicId } from './protection-mode.service';

/** The Markdown rendering of a guide with its download name (8.2 D14). */
export interface MarkdownGuide {
  fileName: string;
  markdown: string;
}

/** The masked form the guide accepts when no intake address can be derived (intake off). */
const MASK_ONLY = '••••';

/**
 * Customer-specific API-mode guides (`api-mode-guide/1`, step API-1 D4, D12 #7) generated by the
 * pure library generator from the connection's own values: provider and tenant, the linked
 * verified domains, the provider journal intake source with its address MASKED (guides are
 * readable with `remediation:read`; the clear address is a journaling credential), the operator's
 * mailbox-access client id, the grant's method, client id and delegated administrator, the
 * feeds settings and the API-mode attestations. The gateway never applies a step.
 */
@Injectable()
export class ApiModeGuideService {
  constructor(
    @Inject(API_CONFIG) private readonly config: ApiModeConfig,
    private readonly repository: ApiModeRepository,
    private readonly addresses: IntakeAddressService,
  ) {}

  now(): Date {
    return new Date();
  }

  private platformClientId(facts: ConnectionFacts): string | null {
    return (
      (facts.provider === 'microsoft_365'
        ? this.config.PROVIDER_M365_MAILBOX_APP_CLIENT_ID
        : this.config.PROVIDER_GOOGLE_MAILBOX_SA_CLIENT_ID) ?? null
    );
  }

  async guide(scope: TenantScope, rawId: unknown): Promise<ApiModeGuide> {
    const facts = await this.repository.connection(scope, parsePublicId(rawId, 'connectionId'));
    if (facts === null) throw connectionNotFound();
    const domains = await this.repository.linkedDomainNames(scope, facts.id);
    const source =
      facts.journalSources.find((s) => s.status !== 'disabled' && s.verifiedAt !== null) ??
      facts.journalSources.find((s) => s.status !== 'disabled') ??
      null;
    const grant = facts.grant !== null && facts.grant.status !== 'revoked' ? facts.grant : null;
    const customer =
      grant?.authMethod === 'customer_app_secret' ||
      grant?.authMethod === 'customer_service_account';
    const codes = new Set(apiModeAttestationsFor(facts.provider).map((a) => a.code));
    return generateApiModeGuide({
      provider: facts.provider,
      connection: {
        publicId: facts.publicId,
        displayName: facts.displayName,
        tenantId: facts.externalTenantId,
      },
      domains,
      journalSource:
        source === null
          ? null
          : {
              publicId: source.publicId,
              displayName: source.displayName,
              kind: source.kind as JournalIntakeKind,
              addressMasked:
                this.addresses.shown(
                  source.publicId,
                  source.addressVersion,
                  source.kind === 'google_workspace_copy',
                  false,
                ).address ?? MASK_ONLY,
            },
      platformClientId: this.platformClientId(facts),
      authMethod: (grant?.authMethod as ProviderAuthMethod | undefined) ?? null,
      grantClientId: customer ? (grant?.clientId ?? null) : null,
      delegatedAdmin: facts.provider === 'google_workspace' ? (grant?.subjectEmail ?? null) : null,
      feeds: { enabled: facts.api?.feedsEnabled ?? false, mode: facts.api?.feedMode ?? 'poll' },
      attestations: attestationsOf(facts.attestations)
        .filter((a) => codes.has(a.code))
        .map((a) => ({ code: a.code, at: a.at })),
      generatedAt: this.now(),
    });
  }

  async markdown(scope: TenantScope, rawId: unknown): Promise<MarkdownGuide> {
    const guide = await this.guide(scope, rawId);
    return { fileName: apiModeGuideFileName(guide), markdown: renderApiModeGuideMarkdown(guide) };
  }
}
