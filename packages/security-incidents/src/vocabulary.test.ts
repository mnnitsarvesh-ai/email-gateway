import { describe, expect, it } from 'vitest';
import {
  ATO_ACCOUNT_KIND_VALUES,
  ATO_RISK_LEVEL_VALUES,
  SECURITY_INCIDENT_CATEGORY_VALUES,
  SECURITY_INCIDENT_CHANGED_FIELD_VALUES,
  SECURITY_INCIDENT_MAX_REASON_CODES,
  SECURITY_INCIDENT_ORIGIN_VALUES,
  SECURITY_INCIDENT_SEVERITY_VALUES,
  SECURITY_INCIDENT_STATUS_VALUES,
  SECURITY_INCIDENT_SUBJECT_TYPE_VALUES,
} from '@email-gateway/event-contracts';
import { ATO_ACCOUNT_KINDS, ATO_RISK_LEVELS } from '@email-gateway/security-contracts';
import {
  INCIDENT_CHANGED_FIELDS,
  INCIDENT_MAX_REASON_CODES,
  SECURITY_INCIDENT_CATEGORIES,
  SECURITY_INCIDENT_ORIGINS,
  SECURITY_INCIDENT_SEVERITIES,
  SECURITY_INCIDENT_STATUSES,
  SECURITY_INCIDENT_SUBJECT_TYPES,
} from './vocabulary';

// WP1 deviation 4: event-contracts mirrors the vocabulary (it depends on neither
// security-contracts nor the database); this package asserts the mirrors are equal.
describe('event-contracts mirrors equal the shared vocabulary', () => {
  it('incident lists', () => {
    expect(SECURITY_INCIDENT_CATEGORY_VALUES).toEqual(SECURITY_INCIDENT_CATEGORIES);
    expect(SECURITY_INCIDENT_SUBJECT_TYPE_VALUES).toEqual(SECURITY_INCIDENT_SUBJECT_TYPES);
    expect(SECURITY_INCIDENT_ORIGIN_VALUES).toEqual(SECURITY_INCIDENT_ORIGINS);
    expect(SECURITY_INCIDENT_STATUS_VALUES).toEqual(SECURITY_INCIDENT_STATUSES);
    expect(SECURITY_INCIDENT_SEVERITY_VALUES).toEqual(SECURITY_INCIDENT_SEVERITIES);
    expect(SECURITY_INCIDENT_CHANGED_FIELD_VALUES).toEqual(INCIDENT_CHANGED_FIELDS);
    expect(SECURITY_INCIDENT_MAX_REASON_CODES).toBe(INCIDENT_MAX_REASON_CODES);
  });

  it('ATO lists', () => {
    expect(ATO_ACCOUNT_KIND_VALUES).toEqual(ATO_ACCOUNT_KINDS);
    expect(ATO_RISK_LEVEL_VALUES).toEqual(ATO_RISK_LEVELS);
  });
});
