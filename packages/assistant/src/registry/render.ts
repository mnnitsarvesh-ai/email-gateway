import { escalationNote } from '../confirmations/escalation';
import { guardNote } from '../confirmations/guards';
import { confirmationSpecOf } from '../confirmations/specs';
import {
  ASSISTANT_PROGRAM_PHASE,
  CONFIRMATION_SUPPORT_PHASE,
  OPERATION_OVERRIDES,
} from './manifest';
import { API_PREFIX, phaseIndex, type RegistryBuild } from './build';
import { NATIVE_TOOLS } from './native';
import {
  PROGRAM_PHASES,
  TOOL_RISKS,
  type MatrixStatus,
  type NotApplicableOperation,
  type OperationTool,
  type PermissionRequirement,
} from './types';

/**
 * Renders the generator outputs (design D3): the TypeScript registry module and the
 * `UI_TO_CHAT_CAPABILITY_MATRIX.md` document. Output is unformatted; the generator formats it
 * with the repository Prettier config so the check never flaps.
 */

export const GENERATE_COMMAND = 'pnpm --filter @email-gateway/assistant registry:generate';
export const CHECK_COMMAND = 'pnpm --filter @email-gateway/assistant registry:check';

export function renderOperationsModule(build: RegistryBuild): string {
  return [
    `// Generated by \`${GENERATE_COMMAND}\` from docs/api/openapi.json,`,
    '// src/registry/manifest.ts and the portal operation usage. Do not edit: change the manifest',
    '// (or the API and its OpenAPI snapshot), then run the command again.',
    "import type { NotApplicableOperation, OperationTool } from './types';",
    '',
    `export const REGISTRY_VERSION = '${build.version}';`,
    '',
    `export const OPERATION_TOOLS: readonly OperationTool[] = ${JSON.stringify(build.tools)};`,
    '',
    `export const NOT_APPLICABLE_OPERATIONS: readonly NotApplicableOperation[] = ${JSON.stringify(build.notApplicable)};`,
    '',
  ].join('\n');
}

function permissionText(requirement: PermissionRequirement): string {
  if (requirement.mode === 'authenticated') return '(authenticated)';
  return `\`${requirement.permissions.join(requirement.mode === 'any' ? ' \\| ' : ' + ')}\``;
}

const cell = (value: string): string => value.replace(/\|/g, '\\|').replace(/\n/g, ' ');

interface MatrixRow {
  module: string;
  pathTemplate: string;
  method: string;
  line: string;
}

/**
 * The confirm cell: the tool's confirmation level plus its risk escalations (step AI-3 D4), e.g.
 * `confirm ↑ high when body.url`.
 */
function confirmCell(tool: OperationTool): string {
  const spec = tool.access === 'write' ? confirmationSpecOf(tool.operationId) : undefined;
  return cell([tool.confirm, ...(spec?.escalate ?? []).map(escalationNote)].join(' '));
}

/**
 * The chat tool cell: the name plus its proposal guards (step AI-3 D3), e.g. `(guard: not self)`,
 * its redacted inputs (step AI-4 D9), e.g. `(redacted: body.sample, …)`, and its omitted inputs
 * (step AI-5 D7), e.g. `(omitted: reveal)`.
 */
function toolCell(tool: OperationTool): string {
  const spec = tool.access === 'write' ? confirmationSpecOf(tool.operationId) : undefined;
  const notes = [...new Set((spec?.guards ?? []).map(guardNote))];
  const omitted = tool.native ? [] : (OPERATION_OVERRIDES[tool.operationId]?.omitInputs ?? []);
  if (omitted.length > 0) notes.push(`omitted: ${omitted.join(', ')}`);
  const redacted = tool.redactParams;
  if (redacted.length > 0)
    notes.push(
      `redacted: ${redacted.join(', ')}, stored as [redacted] in execution and audit rows; the values stay in the conversation until retention purges it`,
    );
  return `\`${tool.name}\`${notes.length > 0 ? ` (${cell(notes.join('; '))})` : ''}`;
}

function toolRow(tool: OperationTool): MatrixRow {
  const cells = [
    cell(tool.portalPages.join('; ') || '(no portal page)'),
    tool.method,
    `\`${tool.pathTemplate.slice(API_PREFIX.length)}\``,
    `\`${tool.operationId}\``,
    permissionText(tool.requirement),
    tool.access === 'read' ? 'R' : 'W',
    tool.risk,
    confirmCell(tool),
    tool.idempotency ?? '',
    tool.status,
    tool.phase,
    toolCell(tool),
    tool.testedBy ? `\`${tool.testedBy}\`` : '-',
  ];
  return { ...tool, line: `| ${cells.join(' | ')} |` };
}

function notApplicableRow(op: NotApplicableOperation, idempotency: string): MatrixRow {
  const cells = [
    cell(op.portalPages.join('; ') || '(no portal page)'),
    op.method,
    `\`${op.pathTemplate.slice(API_PREFIX.length)}\``,
    `\`${op.operationId}\``,
    permissionText(op.requirement),
    op.access === 'read' ? 'R' : 'W',
    op.risk ?? '-',
    '-',
    idempotency,
    'NOT_APPLICABLE',
    '-',
    `- (${cell(op.reason)})`,
    '-',
  ];
  return { ...op, line: `| ${cells.join(' | ')} |` };
}

function countBy<T>(items: readonly T[], key: (item: T) => string): Map<string, number> {
  const out = new Map<string, number>();
  for (const item of items) out.set(key(item), (out.get(key(item)) ?? 0) + 1);
  return out;
}

const HEADER =
  '| Portal page | Method | Path | Operation id | Permission | R/W | Risk | Confirm | Idem | Status | Phase | Chat tool | Test coverage |';
const RULE = `|${' --- |'.repeat(13)}`;

/**
 * The capability matrix. `idempotencyOf` gives the `x-eg-idempotency` of not-applicable
 * operations (tool records carry their own).
 */
export function renderMatrix(
  build: RegistryBuild,
  idempotencyOf: (operationId: string) => string,
): string {
  const total = build.tools.length + build.notApplicable.length;
  const statuses = countBy<{ status: MatrixStatus }>(
    [...build.tools, ...build.notApplicable.map(() => ({ status: 'NOT_APPLICABLE' as const }))],
    (item) => item.status,
  );
  const phases = countBy(build.tools, (tool) => tool.phase);
  const risks = countBy(build.tools, (tool) => tool.risk);
  const critical = build.notApplicable.filter((op) => op.risk === 'critical').length;
  const enabled = build.tools.filter((tool) => tool.enabled);
  const natives = NATIVE_TOOLS;
  const nativeEnabled = natives.filter((tool) => tool.enabled);
  const missing = build.tools.filter((tool) => tool.status === 'MISSING');
  const missingReads = missing.filter((tool) => tool.access === 'read').length;

  const lines: string[] = [
    '# UI-to-chat capability matrix',
    '',
    `Generated by \`${GENERATE_COMMAND}\` from \`docs/api/openapi.json\`, the registry manifest (\`packages/assistant/src/registry/manifest.ts\`) and the portal's operation usage (operation-id strings in \`apps/admin-portal/src/features/**\`, the app shell excluded). **Do not edit by hand**: \`${CHECK_COMMAND}\` (part of the package \`test\`) fails when this file or \`operations.generated.ts\` is stale, and when an OpenAPI operation is not classified. Design: \`docs/plan/steps/28-ai-chat-management.md\` (D3, §4.4, Appendix A is the design-time baseline).`,
    '',
    `Registry version \`${build.version}\`; program phase **${ASSISTANT_PROGRAM_PHASE}** (tools of this phase and earlier are enabled; ${
      phaseIndex(ASSISTANT_PROGRAM_PHASE) >= phaseIndex(CONFIRMATION_SUPPORT_PHASE)
        ? 'writes run only after the user confirms them in a confirmation card (ADR-0093): the model can only propose a write, and each enabled write has a confirmation spec, an impact template and an integration suite'
        : 'writes need the confirmation manager of AI-2'
    }).`,
    '',
    'Every portal action is an API operation (ADR-0063), so this operation-level table is the complete UI-to-chat matrix. Confirm `↑ <risk> when <argument>` marks a conditional risk escalation (the stored confirmation risk is raised when the final arguments touch that field; `<argument> < <field>`, `<argument> → <value>` and `<argument> ≠ <field>` compare the argument with the current value read before the proposal, failing closed when that value is unknown); `(guard: …)` after a chat tool marks a proposal guard (for example `not self`: the tool refuses the signed-in user’s own account; `not requester`: the person who requested an ATO response cannot decide it); `(redacted: …)` marks inputs the platform stores as `[redacted]` in execution and audit rows; `(omitted: …)` marks optional inputs of the operation that are never offered to the model (unmasking and consent inputs stay in the portal); `impactToken` of a confirmed mail-flow change or disconnect is filled by the server from a fresh preview. Statuses: `IMPLEMENTED` (an enabled chat tool with test coverage), `PARTIALLY_IMPLEMENTED` (enabled with limitations), `MISSING` (classified, planned for the phase shown), `NOT_APPLICABLE` (never a chat tool; the reason is given and the chat links to the portal page). Columns: R/W access; risk `read`, `read_audited`, `low`, `medium`, `high`, `critical`; confirm `none`, `confirm`, `confirm+impact`, `confirm+impact+reauth`; Idem = `x-eg-idempotency`; Permission = `x-eg-permissions` (`a \\| b` any of, `a + b` all of).',
    '',
    '## Totals',
    '',
    `- Operations: ${total}; chat tools ${build.tools.length} (enabled ${enabled.length}), not applicable ${build.notApplicable.length} (of which critical, portal only: ${critical}).`,
    `- By status: ${['IMPLEMENTED', 'PARTIALLY_IMPLEMENTED', 'MISSING', 'NOT_APPLICABLE']
      .map((status) => `${status} ${statuses.get(status) ?? 0}`)
      .join(', ')} (MISSING: read ${missingReads}, write ${missing.length - missingReads}).`,
    `- By phase: ${PROGRAM_PHASES.filter((phase) => phases.has(phase))
      .map((phase) => `${phase} ${phases.get(phase)}`)
      .join(', ')}.`,
    `- Native assistant tools (not OpenAPI operations, step AI-R): ${natives.length} (enabled ${nativeEnabled.length}: read ${nativeEnabled.filter((t) => t.access === 'read').length}, write ${nativeEnabled.filter((t) => t.access === 'write').length}); enabled chat tools in all: ${enabled.length + nativeEnabled.length} (read ${[...enabled, ...nativeEnabled].filter((t) => t.access === 'read').length}, write ${[...enabled, ...nativeEnabled].filter((t) => t.access === 'write').length}).`,
    `- By risk (tools): ${TOOL_RISKS.filter((risk) => risks.has(risk))
      .map((risk) => `${risk} ${risks.get(risk)}`)
      .join(', ')}.`,
    '',
  ];

  const rows: MatrixRow[] = [
    ...build.tools.map(toolRow),
    ...build.notApplicable.map((op) => notApplicableRow(op, idempotencyOf(op.operationId))),
  ].sort(
    (a, b) =>
      a.module.localeCompare(b.module, 'en') ||
      a.pathTemplate.localeCompare(b.pathTemplate, 'en') ||
      a.method.localeCompare(b.method, 'en'),
  );
  let module: string | null = null;
  for (const row of rows) {
    if (row.module !== module) {
      if (module !== null) lines.push('');
      module = row.module;
      lines.push(`## Module \`${module}\``, '', HEADER, RULE);
    }
    lines.push(row.line);
  }
  lines.push(
    '',
    '## Native assistant tools',
    '',
    'Registry records that are not OpenAPI operations (step AI-R, design `docs/plan/steps/31-ai-chat-reports.md` D1, ADR-0095): the api runs them with its own services (`report_generate`: a fixed composition of loopback reads of the report routes, rendered server-side to static HTML; `report_send_email`: a confirmed email of a generated report through the notification mailer). Their `native:` paths never reach the loopback.',
    '',
    NATIVE_HEADER,
    `|${' --- |'.repeat(11)}`,
    ...natives.map(nativeRow),
    '',
  );
  return lines.join('\n');
}

const NATIVE_HEADER =
  '| Chat tool | Operation id | Path | Permission | R/W | Risk | Confirm | Status | Phase | Portal page | Test coverage |';

function nativeRow(tool: OperationTool): string {
  const cells = [
    toolCell(tool),
    `\`${tool.operationId}\``,
    `\`${tool.pathTemplate}\``,
    permissionText(tool.requirement),
    tool.access === 'read' ? 'R' : 'W',
    tool.risk,
    confirmCell(tool),
    tool.status,
    tool.phase,
    tool.portalRoute ?? '-',
    tool.testedBy ? `\`${tool.testedBy}\`` : '-',
  ];
  return `| ${cells.join(' | ')} |`;
}
