import { type TableLoadStat } from './load';
import { EXPLAIN_COLUMNS, type ExplainRow, type QueryResult } from './run';

export interface PerfEnvironment {
  mysqlVersion: string;
  bufferPoolBytes: number;
  dockerMemoryBytes: number | null;
  host: string;
  node: string;
}

export interface PerfReportInput {
  generatedAt: Date;
  command: string;
  messages: number;
  organizations: number;
  days: number;
  runs: number;
  environment: PerfEnvironment;
  /** Throwaway schema the run used (`<db>_perf`). */
  schema: string;
  migrateMs: number;
  maintenanceMs: number;
  loadMs: number;
  analyzeMs: number;
  loadStats: TableLoadStat[];
  tables: { table: string; rows: number; partitions: number }[];
  replica: {
    measured: boolean;
    maxLagSeconds: number | null;
    samples: number;
    unavailable: number;
    catchUpSeconds: number | null;
  };
  results: QueryResult[];
}

const GiB = 1024 ** 3;
const MiB = 1024 ** 2;
const fmt = (n: number, digits = 2) => n.toFixed(digits);
const int = (n: number) => Math.round(n).toLocaleString('en-US');
/** Text of a scalar result value (strings, numbers, bigints, dates). */
export const text = (value: unknown): string => {
  if (value === null || value === undefined) return '';
  if (value instanceof Date) return value.toISOString();
  switch (typeof value) {
    case 'string':
      return value;
    case 'number':
    case 'bigint':
    case 'boolean':
      return value.toString();
    default:
      return JSON.stringify(value) ?? '';
  }
};
const cell = (value: unknown) => text(value).replaceAll('|', '\\|').replaceAll('\n', ' ');

const SHOWN_COLUMNS = EXPLAIN_COLUMNS.filter((c) => c !== 'possible_keys');

function aliasMap(sql: string): Map<string, string> {
  const map = new Map<string, string>();
  const pattern = /\b(?:FROM|JOIN|INTO)\s+`?([a-z_]+)`?(?:\s+(?:AS\s+)?([a-z]\w*))?/gi;
  for (const match of sql.matchAll(pattern)) {
    const table = match[1]!;
    map.set(table, table);
    const alias = match[2];
    if (alias && !/^(WHERE|JOIN|ON|ORDER|GROUP|LIMIT|VALUES|SET)$/i.test(alias))
      map.set(alias, table);
  }
  return map;
}

/** "p202610,p202611 (2 of 9)" per table in an EXPLAIN result. */
export function prunedPartitions(
  explain: ExplainRow[],
  sql: string,
  totals: Map<string, number>,
): string[] {
  const aliases = aliasMap(sql);
  return explain
    .filter((row) => row.table)
    .map((row) => {
      const alias = String(row.table);
      const table = aliases.get(alias) ?? alias;
      const total = totals.get(table);
      const partitions = row.partitions ? text(row.partitions).split(',') : [];
      if (!total || total <= 1) return `\`${table}\`: not partitioned`;
      return `\`${table}\`: ${partitions.length} of ${total} partitions (${partitions.join(', ')})`;
    });
}

function explainTable(rows: ExplainRow[]): string {
  const header = `| ${SHOWN_COLUMNS.join(' | ')} |`;
  const divider = `| ${SHOWN_COLUMNS.map(() => '---').join(' | ')} |`;
  const body = rows.map((row) => `| ${SHOWN_COLUMNS.map((c) => cell(row[c])).join(' | ')} |`);
  return [header, divider, ...body].join('\n');
}

const showParam = (p: unknown) => {
  const text = typeof p === 'string' ? `'${p}'` : String(p);
  return text.length > 60 ? `${text.slice(0, 57)}…` : text;
};

export function renderReport(input: PerfReportInput): string {
  const totals = new Map(input.tables.map((t) => [t.table, t.partitions]));
  const env = input.environment;
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(
    '# Database performance report',
    '',
    `Generated by \`${input.command}\` on ${input.generatedAt.toISOString()} (D8 in [the step design](../plan/steps/01-database.md#d8-performance-test)). The queries are explained in [query-examples.md](query-examples.md).`,
    '',
    '> **Caveat:** these numbers come from a developer laptop running MySQL in Docker. They are a **baseline** for spotting regressions and checking plans and partition pruning, **not** a statement of production capacity. Production sizing is validated on RDS/Aurora in step 10.2.',
    '',
    '## Environment',
    '',
    '| Item | Value |',
    '| --- | --- |',
    `| MySQL | ${env.mysqlVersion} (primary, in Docker) |`,
    `| InnoDB buffer pool | ${int(env.bufferPoolBytes / MiB)} MiB |`,
    `| Docker VM memory | ${env.dockerMemoryBytes === null ? 'unknown' : `${fmt(env.dockerMemoryBytes / GiB, 1)} GiB`} |`,
    `| Host | ${cell(env.host)} |`,
    `| Node.js (load generator) | ${env.node} |`,
    `| Data set | ${int(input.messages)} messages, ${input.organizations} organizations (Zipf-skewed), last ${input.days} days |`,
    `| Timed runs per query | ${input.runs} (after 2 warm-up runs), client-side wall time including the Prisma round trip |`,
    '',
    '## Setup and load',
    '',
    '| Phase | Duration |',
    '| --- | --- |',
    `| \`prisma migrate deploy\` into \`${input.schema}\` | ${fmt(input.migrateMs / 1000, 1)} s |`,
    `| Partition maintenance (bootstrap 4 months back) | ${fmt(input.maintenanceMs / 1000, 1)} s |`,
    `| Synthetic load | ${fmt(input.loadMs / 1000, 1)} s |`,
    `| \`ANALYZE TABLE\` | ${fmt(input.analyzeMs / 1000, 1)} s |`,
    '',
    'Load throughput: multi-row `INSERT` with 1,000 rows per statement through one connection. The time is per table, summed over its statements.',
    '',
    '| Table | Rows | Seconds | Rows/s |',
    '| --- | ---: | ---: | ---: |',
  );
  for (const s of [...input.loadStats].sort((a, b) => b.rows - a.rows)) {
    push(
      `| \`${s.table}\` | ${int(s.rows)} | ${fmt(s.ms / 1000, 1)} | ${s.ms > 0 ? int((s.rows / s.ms) * 1000) : '–'} |`,
    );
  }
  const replica = input.replica;
  push(
    '',
    '### Replica lag during the load',
    '',
    replica.measured
      ? `Sampled \`SHOW REPLICA STATUS\` on the replica (\`DATABASE_READ_URL\`) once per second: **max \`Seconds_Behind_Source\` = ${replica.maxLagSeconds ?? 'n/a'} s** over ${replica.samples} samples (${replica.unavailable} without a value). The replica caught up ${replica.catchUpSeconds === null ? '(not within the wait limit)' : `${fmt(replica.catchUpSeconds, 0)} s after the load finished`}. The api reader falls back to the writer above \`DATABASE_READ_MAX_LAG_SECONDS\`, so a bulk load like this one moves control-plane reads to the primary until the replica catches up.`
      : 'Not measured: `DATABASE_READ_URL` was not set.',
    '',
    '## Row counts after the load',
    '',
    '| Table | Rows | Partitions |',
    '| --- | ---: | ---: |',
  );
  for (const t of input.tables)
    push(`| \`${t.table}\` | ${int(t.rows)} | ${t.partitions > 1 ? t.partitions : '–'} |`);

  push(
    '',
    '## Query summary',
    '',
    '| Query | Median (ms) | p95 (ms) | Rows | Partitions read |',
    '| --- | ---: | ---: | ---: | --- |',
  );
  for (const r of input.results) {
    const pruning = r.plans
      .flatMap((p) =>
        typeof p.explain === 'string' ? [] : prunedPartitions(p.explain, p.sql, totals),
      )
      .filter((s) => !s.endsWith('not partitioned'))
      .map((s) => s.replace(/ \(.*\)$/, ''));
    push(
      `| ${r.query.id}: ${cell(r.query.title)} | ${fmt(r.medianMs)} | ${fmt(r.p95Ms)} | ${r.rowsReturned} | ${cell([...new Set(pruning)].join('; ') || 'not partitioned')} |`,
    );
  }

  push('', '## Queries', '');
  for (const r of input.results) {
    push(
      `### ${r.query.id}: ${r.query.title}`,
      '',
      r.query.note,
      '',
      `Median **${fmt(r.medianMs)} ms**, p95 **${fmt(r.p95Ms)} ms** over ${r.timingsMs.length} runs (all steps).`,
      '',
    );
    for (const plan of r.plans) {
      push(`#### ${plan.label}`, '', '```sql', plan.sql, '```', '');
      if (plan.params.length > 0) push(`Parameters: ${plan.params.map(showParam).join(', ')}`, '');
      if (typeof plan.explain === 'string') {
        push(plan.explain, '');
      } else {
        push(
          'Partitions:',
          '',
          ...prunedPartitions(plan.explain, plan.sql, totals).map((s) => `- ${s}`),
          '',
        );
        push(explainTable(plan.explain), '');
      }
      push(
        '`EXPLAIN FORMAT=TREE`:',
        '',
        '```text',
        plan.tree,
        '```',
        '',
        '`EXPLAIN ANALYZE`:',
        '',
        '```text',
        plan.analyze,
        '```',
        '',
      );
    }
  }
  return `${lines.join('\n')}\n`;
}
