import {
  DEFAULT_PLAN_OPTIONS,
  type ExistingPartition,
  type PartitionAction,
  type PlanOptions,
  formatBound,
  planPartitionChanges,
} from './planner';
import {
  PARTITION_REGISTRY,
  type PartitionSpec,
  RETENTION_PURGES,
  type RetentionPurgeConfig,
  assertValidSpec,
} from './registry';

/**
 * Applies partition plans and retention purges (D3). Runs as the migrator account
 * (MIGRATION_DATABASE_URL). Every step is idempotent: a second run right after a successful
 * one plans no partition changes and purges nothing.
 *
 * Identifiers interpolated into SQL come only from the registry (validated by
 * assertValidSpec) or from partition names generated by the planner or read from
 * information_schema and checked against a strict pattern. Values go through placeholders.
 *
 * Concurrency and blocking (apply mode):
 * - Runs are serialized by a MySQL advisory lock named after the schema (GET_LOCK with no
 *   wait). Compose db-migrate, the CronJob, a manual `db:partitions apply` and CI can overlap;
 *   the run that does not get the lock skips with a warning and plans nothing.
 * - Partition DDL waits for the table's metadata lock at most `lockWaitTimeoutSeconds`
 *   (SET SESSION lock_wait_timeout). Without it, a long transaction on a hot table would make
 *   the ALTER wait for up to a year while every later query on that table queues behind it.
 *   A timeout is recorded as a per-table failure and the next run retries.
 * Both are per-connection, so the client must use exactly one connection: build it with
 * createMaintenanceClientUrl() (connection_limit=1). Before every DDL statement the executor
 * checks that the advisory lock is held by the current connection and aborts otherwise.
 */

/** The subset of PrismaClient the executor needs (a fake implements it in unit tests). */
export interface SqlClient {
  $queryRawUnsafe<T = unknown>(query: string, ...values: unknown[]): Promise<T>;
  $executeRawUnsafe(query: string, ...values: unknown[]): Promise<number>;
}

/** The subset of a pino logger the executor needs. */
export interface MaintenanceLogger {
  info(obj: object, msg?: string): void;
  warn(obj: object, msg?: string): void;
  error(obj: object, msg?: string): void;
}

export type MaintenanceMode = 'plan' | 'apply';

export interface MaintenanceOptions {
  client: SqlClient;
  logger: MaintenanceLogger;
  mode: MaintenanceMode;
  now?: Date;
  /** Tables to manage. Defaults to the registry; tests pass scratch tables. */
  specs?: readonly PartitionSpec[];
  plan?: Partial<PlanOptions>;
  /** Run the D3.4 retention purges (default true). */
  purge?: boolean;
  purgeOptions?: Partial<RetentionPurgeConfig>;
  sleep?: (ms: number) => Promise<void>;
  /** Metadata-lock wait bound for partition DDL, in seconds (default 5). */
  lockWaitTimeoutSeconds?: number;
}

export interface StatementRecord {
  table: string;
  kind: 'split-pmax' | 'drop' | 'purge';
  sql: string;
  applied: boolean;
}

export interface MaintenanceResult {
  ok: boolean;
  /** True when another run held the advisory lock, so this run did nothing (apply mode). */
  skippedLockHeld: boolean;
  /** Planned partition actions per table (empty when nothing to do). */
  actions: { table: string; action: PartitionAction }[];
  statements: StatementRecord[];
  /** Partitions whose drop was skipped by a guard. */
  skippedDrops: { table: string; partition: string; reason: string }[];
  purged: { table: string; rows: number; batches: number; capped: boolean }[];
  errors: { table: string; message: string }[];
}

const PARTITION_NAME = /^p(max|\d{6}|\d{8})$/;

export const DEFAULT_LOCK_WAIT_TIMEOUT_SECONDS = 5;

/** Advisory lock name: one per schema, so maintenance of the perf schema never blocks the
 * gateway schema. GET_LOCK names are server-wide and at most 64 characters. */
const LOCK_NAME_SQL = "LEFT(CONCAT('partition_maintenance:', DATABASE()), 64)";

/** Watermark row for the message_identities purge (table maintenance_watermarks). */
export const REGISTRY_WATERMARK = 'message_identities.purged_below';

/**
 * Returns `url` with connection_limit=1: the advisory lock and lock_wait_timeout are
 * per-connection, so the maintenance client must never spread statements over a pool.
 */
export function createMaintenanceClientUrl(url: string): string {
  const parsed = new URL(url);
  parsed.searchParams.set('connection_limit', '1');
  return parsed.toString();
}

const q = (identifier: string) => `\`${identifier}\``;

function assertPartitionName(name: string): void {
  if (!PARTITION_NAME.test(name)) throw new Error(`Refusing unexpected partition name ${name}`);
}

export function buildSplitSql(
  table: string,
  partitions: { name: string; lessThan: string }[],
): string {
  const parts = partitions.map((p) => {
    assertPartitionName(p.name);
    if (!/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(p.lessThan)) {
      throw new Error(`Refusing unexpected partition bound ${p.lessThan}`);
    }
    return `PARTITION ${q(p.name)} VALUES LESS THAN ('${p.lessThan}')`;
  });
  return (
    `ALTER TABLE ${q(table)} REORGANIZE PARTITION ${q('pmax')} INTO (` +
    `${parts.join(', ')}, PARTITION ${q('pmax')} VALUES LESS THAN (MAXVALUE))`
  );
}

export function buildDropSql(table: string, partitions: string[]): string {
  for (const name of partitions) {
    assertPartitionName(name);
    if (name === 'pmax') throw new Error('Refusing to drop pmax');
  }
  return `ALTER TABLE ${q(table)} DROP PARTITION ${partitions.map(q).join(', ')}`;
}

interface PartitionRow {
  tableName: string;
  partitionName: string;
  description: string | null;
  tableRows: bigint | number | null;
}

async function readPartitions(client: SqlClient): Promise<Map<string, PartitionRow[]>> {
  const rows = await client.$queryRawUnsafe<PartitionRow[]>(
    `SELECT TABLE_NAME AS tableName, PARTITION_NAME AS partitionName,
            PARTITION_DESCRIPTION AS description, TABLE_ROWS AS tableRows
       FROM information_schema.PARTITIONS
      WHERE TABLE_SCHEMA = DATABASE() AND PARTITION_NAME IS NOT NULL
      ORDER BY TABLE_NAME, PARTITION_ORDINAL_POSITION`,
  );
  const byTable = new Map<string, PartitionRow[]>();
  for (const row of rows) {
    const list = byTable.get(row.tableName) ?? [];
    list.push(row);
    byTable.set(row.tableName, list);
  }
  return byTable;
}

const message = (err: unknown) => (err instanceof Error ? err.message : String(err));

const defaultSleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

/** Runs partition maintenance for every spec, then the retention purges. Never throws for a
 * per-table failure: it records the error, continues with the next table and returns ok=false. */
export async function runPartitionMaintenance(
  options: MaintenanceOptions,
): Promise<MaintenanceResult> {
  const { client, logger, mode } = options;
  const now = options.now ?? new Date();
  const specs = options.specs ?? PARTITION_REGISTRY;
  const planOptions: PlanOptions = { ...DEFAULT_PLAN_OPTIONS, ...options.plan };
  const apply = mode === 'apply';
  const lockWaitTimeout = options.lockWaitTimeoutSeconds ?? DEFAULT_LOCK_WAIT_TIMEOUT_SECONDS;
  if (!Number.isInteger(lockWaitTimeout) || lockWaitTimeout < 1 || lockWaitTimeout > 3600) {
    throw new Error(`Invalid lock wait timeout ${lockWaitTimeout}`);
  }
  const result: MaintenanceResult = {
    ok: true,
    skippedLockHeld: false,
    actions: [],
    statements: [],
    skippedDrops: [],
    purged: [],
    errors: [],
  };
  const fail = (table: string, err: unknown) => {
    result.ok = false;
    result.errors.push({ table, message: message(err) });
    logger.error({ table, err: message(err) }, 'partition maintenance failed for table');
  };

  for (const spec of specs) assertValidSpec(spec);

  if (apply) {
    const [lock] = await client.$queryRawUnsafe<{ acquired: bigint | number | null }[]>(
      `SELECT GET_LOCK(${LOCK_NAME_SQL}, 0) AS acquired`,
    );
    if (Number(lock?.acquired ?? 0) !== 1) {
      result.skippedLockHeld = true;
      logger.warn({}, 'another partition maintenance run holds the lock; skipping this run');
      return result;
    }
  }
  try {
    if (apply) {
      await client.$executeRawUnsafe(`SET SESSION lock_wait_timeout = ${lockWaitTimeout}`);
    }
    await maintain();
  } finally {
    if (apply) {
      await client
        .$queryRawUnsafe(`SELECT RELEASE_LOCK(${LOCK_NAME_SQL}) AS released`)
        .catch((err: unknown) =>
          logger.warn({ err: message(err) }, 'could not release the maintenance lock'),
        );
    }
  }
  return result;

  /** Throws unless this connection holds the advisory lock (guards against a pooled client). */
  async function assertLockHeld() {
    const [row] = await client.$queryRawUnsafe<{ mine: bigint | number | null }[]>(
      `SELECT IS_USED_LOCK(${LOCK_NAME_SQL}) = CONNECTION_ID() AS mine`,
    );
    if (Number(row?.mine ?? 0) !== 1) {
      throw new Error(
        'maintenance lock is not held by this connection; use a single-connection client',
      );
    }
  }

  async function maintain() {
    const partitionsByTable = await readPartitions(client);

    for (const spec of specs) {
      const { table } = spec;
      try {
        const rows = partitionsByTable.get(table);
        if (!rows || rows.length === 0) {
          throw new Error('table is missing or not partitioned in the current schema');
        }
        const existing: ExistingPartition[] = rows.map((r) => ({
          name: r.partitionName,
          description: r.description ?? '',
        }));
        const actions = planPartitionChanges(spec, existing, now, planOptions);
        if (actions.length === 0) {
          logger.info({ table, partitions: rows.length }, 'partitions up to date');
          continue;
        }
        for (const action of actions) {
          result.actions.push({ table, action });
          if (action.kind === 'split-pmax') {
            await split(spec, action.partitions, rows);
          } else {
            await drop(spec, action.partitions);
          }
        }
      } catch (err) {
        fail(table, err);
      }
    }

    async function split(
      spec: PartitionSpec,
      partitions: { name: string; lessThan: string }[],
      rows: PartitionRow[],
    ) {
      const sql = buildSplitSql(spec.table, partitions);
      // Rows already in pmax are copied by REORGANIZE: warn, because it means maintenance fell
      // behind (or data arrived with a far-future timestamp), but split anyway.
      const stray = await client.$queryRawUnsafe<unknown[]>(
        `SELECT 1 FROM ${q(spec.table)} PARTITION (${q('pmax')}) LIMIT 1`,
      );
      if (stray.length > 0) {
        const estimate = rows.find((r) => r.partitionName === 'pmax')?.tableRows ?? null;
        logger.warn(
          { table: spec.table, pmaxRowEstimate: estimate === null ? null : Number(estimate) },
          'pmax already contains rows; the split copies them',
        );
      }
      if (apply) {
        await assertLockHeld();
        await client.$executeRawUnsafe(sql);
      }
      result.statements.push({ table: spec.table, kind: 'split-pmax', sql, applied: apply });
      logger.info(
        {
          table: spec.table,
          created: partitions.map((p) => p.name),
          upTo: partitions.at(-1)?.lessThan,
          applied: apply,
        },
        apply ? 'partitions created' : 'would create partitions',
      );
    }

    async function drop(spec: PartitionSpec, partitions: string[]) {
      const allowed: string[] = [];
      for (const name of partitions) {
        if (spec.guard?.kind === 'no-null-rows') {
          assertPartitionName(name);
          const blocking = await client.$queryRawUnsafe<unknown[]>(
            `SELECT 1 FROM ${q(spec.table)} PARTITION (${q(name)}) WHERE ${q(spec.guard.column)} IS NULL LIMIT 1`,
          );
          if (blocking.length > 0) {
            result.ok = false;
            result.skippedDrops.push({
              table: spec.table,
              partition: name,
              reason: spec.guard.description,
            });
            logger.error(
              { table: spec.table, partition: name, guard: spec.guard.description },
              'expired partition not dropped: guard failed',
            );
            continue;
          }
        }
        allowed.push(name);
      }
      if (allowed.length === 0) return;
      const sql = buildDropSql(spec.table, allowed);
      if (apply) {
        await assertLockHeld();
        await client.$executeRawUnsafe(sql);
      }
      result.statements.push({ table: spec.table, kind: 'drop', sql, applied: apply });
      logger.info(
        { table: spec.table, dropped: allowed, applied: apply },
        apply ? 'expired partitions dropped' : 'would drop expired partitions',
      );
    }

    if (options.purge ?? true) {
      await runRetentionPurges(options, now, result, fail);
    }
  }
}

async function runRetentionPurges(
  options: MaintenanceOptions,
  now: Date,
  result: MaintenanceResult,
  fail: (table: string, err: unknown) => void,
) {
  const { client, logger, mode } = options;
  const cfg: RetentionPurgeConfig = { ...RETENTION_PURGES, ...options.purgeOptions };
  if (!Number.isInteger(cfg.batchSize) || cfg.batchSize < 1) {
    throw new Error(`Invalid purge batch size ${cfg.batchSize}`);
  }
  const sleep = options.sleep ?? defaultSleep;
  const apply = mode === 'apply';

  const purge = async (table: string, sql: string, values: unknown[]) => {
    const record: StatementRecord = { table, kind: 'purge', sql, applied: apply };
    result.statements.push(record);
    if (!apply) {
      logger.info({ table, sql, values: values.map(String) }, 'would purge');
      return;
    }
    let rows = 0;
    let batches = 0;
    let affected = cfg.batchSize;
    while (affected === cfg.batchSize && batches < cfg.maxBatches) {
      if (batches > 0) await sleep(cfg.sleepMs);
      affected = await client.$executeRawUnsafe(sql, ...values);
      rows += affected;
      batches += 1;
    }
    const capped = affected === cfg.batchSize;
    result.purged.push({ table, rows, batches, capped });
    if (capped) {
      logger.warn(
        { table, rows, batches },
        'retention purge hit its per-run cap; the rest is purged on the next run',
      );
    } else {
      logger.info({ table, rows, batches }, 'retention purge complete');
    }
  };

  try {
    const cutoff = new Date(now.getTime() - cfg.idempotencyDays * 24 * 60 * 60 * 1000);
    await purge(
      'message_idempotency',
      `DELETE FROM ${q('message_idempotency')} WHERE ${q('processed_at')} < ? LIMIT ${cfg.batchSize}`,
      [formatBound(cutoff)],
    );
  } catch (err) {
    fail('message_idempotency', err);
  }

  try {
    await purgeRegistry(options, cfg, result, sleep);
  } catch (err) {
    fail('message_identities', err);
  }
}

/** The batched registry purge. Values: [from, to). Exported for tests and docs. */
export const REGISTRY_PURGE_SQL =
  `DELETE FROM ${q('message_identities')} WHERE ${q('id')} >= ? AND ${q('id')} < ?` +
  ` AND NOT EXISTS (SELECT 1 FROM ${q('email_archives')} a` +
  ` WHERE a.${q('message_id')} = ${q('message_identities')}.${q('id')} AND a.${q('deleted_at')} IS NULL)` +
  ` AND NOT EXISTS (SELECT 1 FROM ${q('quarantine_messages')} qm` +
  ` WHERE qm.${q('message_id')} = ${q('message_identities')}.${q('id')})`;

const WATERMARK_UPSERT_SQL =
  `INSERT INTO ${q('maintenance_watermarks')} (${q('name')}, ${q('value')}, ${q('updated_at')})` +
  ` VALUES (?, ?, NOW(3)) AS new ON DUPLICATE KEY UPDATE` +
  ` ${q('value')} = GREATEST(${q('maintenance_watermarks')}.${q('value')}, new.${q('value')}),` +
  ` ${q('updated_at')} = new.${q('updated_at')}`;

const toBigInt = (v: bigint | number | string | null | undefined) =>
  v === null || v === undefined ? null : BigInt(v);

/**
 * Deletes registry rows (message_identities) whose message partitions were dropped (D3.4).
 *
 * Registry ids are allocated in time order, so every id below MIN(email_messages.id) belongs to
 * a message whose core rows are gone. A row is kept while a live email_archives row or any
 * quarantine_messages row references it: archives are never auto-dropped and quarantine can
 * outlive the core tier, and both are reached by message public id through the registry.
 *
 * The purge walks id ranges of `batchSize` from a watermark (maintenance_watermarks), so the
 * rows it keeps are examined once rather than on every run. Whoever later deletes the last
 * archive or quarantine reference to a message below the watermark (steps 4.x, 8.1) deletes
 * its registry row in the same transaction. With no messages at all there is no safe bound,
 * so nothing is purged.
 */
async function purgeRegistry(
  options: MaintenanceOptions,
  cfg: RetentionPurgeConfig,
  result: MaintenanceResult,
  sleep: (ms: number) => Promise<void>,
) {
  const { client, logger, mode } = options;
  const apply = mode === 'apply';
  const table = 'message_identities';

  const [msg] = await client.$queryRawUnsafe<{ minId: bigint | number | null }[]>(
    `SELECT MIN(${q('id')}) AS minId FROM ${q('email_messages')}`,
  );
  const cutoff = toBigInt(msg?.minId);
  if (cutoff === null) {
    logger.info({ table }, 'no messages; registry purge skipped');
    return;
  }
  const [mark] = await client.$queryRawUnsafe<{ value: bigint | number | null }[]>(
    `SELECT ${q('value')} AS value FROM ${q('maintenance_watermarks')} WHERE ${q('name')} = ?`,
    REGISTRY_WATERMARK,
  );
  let from = toBigInt(mark?.value);
  if (from === null) {
    const [first] = await client.$queryRawUnsafe<{ minId: bigint | number | null }[]>(
      `SELECT MIN(${q('id')}) AS minId FROM ${q(table)}`,
    );
    from = toBigInt(first?.minId);
  }
  result.statements.push({ table, kind: 'purge', sql: REGISTRY_PURGE_SQL, applied: apply });
  if (from === null || from >= cutoff) {
    logger.info({ table, cutoff: String(cutoff) }, 'registry purge: nothing below the cutoff');
    if (apply) result.purged.push({ table, rows: 0, batches: 0, capped: false });
    return;
  }
  if (!apply) {
    logger.info(
      { table, from: String(from), cutoff: String(cutoff) },
      'would purge unreferenced registry rows in this id range',
    );
    return;
  }

  const step = BigInt(cfg.batchSize);
  let next: bigint = from;
  let rows = 0;
  let batches = 0;
  while (next < cutoff && batches < cfg.maxBatches) {
    if (batches > 0) await sleep(cfg.sleepMs);
    const to: bigint = next + step < cutoff ? next + step : cutoff;
    rows += await client.$executeRawUnsafe(REGISTRY_PURGE_SQL, next, to);
    await client.$executeRawUnsafe(WATERMARK_UPSERT_SQL, REGISTRY_WATERMARK, to);
    batches += 1;
    next = to;
  }
  const capped = next < cutoff;
  result.purged.push({ table, rows, batches, capped });
  if (capped) {
    logger.warn(
      { table, rows, batches, resumeFrom: String(next) },
      'retention purge hit its per-run cap; the rest is purged on the next run',
    );
  } else {
    logger.info({ table, rows, batches }, 'retention purge complete');
  }
}
