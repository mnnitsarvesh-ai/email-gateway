#!/usr/bin/env node
// Creates .env from .env.example with freshly generated local secrets.
// Refuses to overwrite an existing .env unless --force is given.
//
// Directives (the whole value of a line in .env.example):
//   __GENERATE__ / __GENERATE_<n>__  random hex secret (48 / n characters);
//   __X25519_PRIVATE__               a fresh X25519 key pair; writes the private key (PKCS#8 DER,
//                                    base64url) and remembers the pair (step 4.6 X12:
//                                    SANDBOX_ARTIFACT_PRIVATE_KEY);
//   __X25519_PUBLIC_OF_PREVIOUS__    the public key (SPKI DER, base64url) of the most recently
//                                    generated pair (SANDBOX_ARTIFACT_PUBLIC_KEY); an error when no
//                                    __X25519_PRIVATE__ line precedes it.
//   ${VAR}                           the value of an earlier key.
// Generated values are written to .env only, never printed.
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, '.env');
const force = process.argv.includes('--force');

if (existsSync(target) && !force) {
  console.error(
    '.env already exists; re-run with --force to regenerate (this rotates all secrets).',
  );
  process.exit(1);
}

const values = new Map();
/** The SPKI DER (base64url) of the last pair generated by __X25519_PRIVATE__. */
let lastX25519Public = null;
const lines = readFileSync(join(root, '.env.example'), 'utf8')
  .split('\n')
  .map((line) => {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (!match) return line;
    const [, key, raw] = match;
    if (raw === '__X25519_PRIVATE__') {
      const { privateKey, publicKey } = generateKeyPairSync('x25519');
      lastX25519Public = publicKey.export({ format: 'der', type: 'spki' }).toString('base64url');
      const value = privateKey.export({ format: 'der', type: 'pkcs8' }).toString('base64url');
      values.set(key, value);
      return `${key}=${value}`;
    }
    if (raw === '__X25519_PUBLIC_OF_PREVIOUS__') {
      if (lastX25519Public === null) {
        throw new Error(
          `${key}: __X25519_PUBLIC_OF_PREVIOUS__ needs a preceding __X25519_PRIVATE__`,
        );
      }
      values.set(key, lastX25519Public);
      return `${key}=${lastX25519Public}`;
    }
    // Hex secrets are URL-safe, so they can be embedded in connection strings unescaped.
    // __GENERATE__ is 48 hex characters; __GENERATE_<n>__ is n (for length-limited secrets).
    const generate = /^__GENERATE(?:_(\d+))?__$/.exec(raw);
    const length = generate ? Number(generate[1] ?? 48) : 0;
    let value = generate
      ? randomBytes(Math.ceil(length / 2))
          .toString('hex')
          .slice(0, length)
      : raw;
    value = value.replace(/\$\{([A-Z0-9_]+)\}/g, (_, ref) => {
      if (!values.has(ref)) throw new Error(`${key} references ${ref} before it is defined`);
      return values.get(ref);
    });
    values.set(key, value);
    return `${key}=${value}`;
  });

writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.log(`Wrote ${target} (mode 600).`);
